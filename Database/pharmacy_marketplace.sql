-- ---------------------------------------------------------------------------
-- 6. PAYMENTS
-- ---------------------------------------------------------------------------

CREATE TABLE payments (
    payment_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_id BIGINT UNSIGNED NOT NULL,
    payment_method ENUM('BANK_TRANSFER', 'CASH_ON_DELIVERY') NOT NULL,
    payment_status ENUM('PENDING', 'PAID', 'FAILED', 'REFUNDED', 'PARTIALLY_REFUNDED') NOT NULL DEFAULT 'PENDING',
    amount DECIMAL(14,2) NOT NULL,
    transaction_reference VARCHAR(255) NULL,
    paid_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (payment_id),
    UNIQUE KEY uq_payments_order (order_id),
    UNIQUE KEY uq_payments_transaction_reference (transaction_reference),
    KEY idx_payments_status (payment_status, created_at),
    CONSTRAINT fk_payments_order
        FOREIGN KEY (order_id) REFERENCES customer_orders(order_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_payments_amount CHECK (amount >= 0)
) ENGINE=InnoDB;

CREATE TABLE payment_proofs (
    proof_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    payment_id BIGINT UNSIGNED NOT NULL,
    image_path VARCHAR(500) NOT NULL,
    verification_status ENUM('PENDING', 'VERIFIED', 'REJECTED') NOT NULL DEFAULT 'PENDING',
    verified_by BIGINT UNSIGNED NULL,
    verification_notes TEXT NULL,
    submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    verified_at DATETIME NULL,
    PRIMARY KEY (proof_id),
    KEY idx_payment_proofs_payment (payment_id, submitted_at),
    CONSTRAINT fk_payment_proofs_payment
        FOREIGN KEY (payment_id) REFERENCES payments(payment_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_payment_proofs_verifier
        FOREIGN KEY (verified_by) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------------
-- 7. SHIPMENTS AND COURIER TRACKING
-- ---------------------------------------------------------------------------

CREATE TABLE shipments (
    shipment_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    pharmacy_order_id BIGINT UNSIGNED NOT NULL,
    courier_name VARCHAR(100) NOT NULL,
    tracking_number VARCHAR(255) NULL,
    delivery_status ENUM('PENDING', 'PICKED_UP', 'IN_TRANSIT', 'DELIVERED', 'FAILED', 'RETURNED', 'CANCELLED') NOT NULL DEFAULT 'PENDING',
    shipped_at DATETIME NULL,
    delivered_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (shipment_id),
    UNIQUE KEY uq_shipment_courier_tracking (courier_name, tracking_number),
    KEY idx_shipments_pharmacy_order (pharmacy_order_id),
    KEY idx_shipments_status (delivery_status, created_at),
    CONSTRAINT fk_shipments_pharmacy_order
        FOREIGN KEY (pharmacy_order_id) REFERENCES pharmacy_orders(pharmacy_order_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE shipment_tracking (
    tracking_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    shipment_id BIGINT UNSIGNED NOT NULL,
    status VARCHAR(100) NOT NULL,
    location VARCHAR(255) NULL,
    description TEXT NULL,
    event_time DATETIME NOT NULL,
    received_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tracking_id),
    KEY idx_shipment_tracking_timeline (shipment_id, event_time),
    CONSTRAINT fk_shipment_tracking_shipment
        FOREIGN KEY (shipment_id) REFERENCES shipments(shipment_id)
        ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

