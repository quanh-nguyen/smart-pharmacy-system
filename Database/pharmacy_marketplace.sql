-- ============================================================================
-- Pharmacy marketplace database (MySQL 8.0.16+ / 8.4)
-- Demo schema + sample data for a multi-pharmacy medicine ordering platform.
--
-- IMPORTANT:
--   This is a first-initialization schema + demo-data script. It does NOT drop
--   the database or delete existing data. Docker's MySQL entrypoint runs it
--   only when the named data volume is initialized for the first time.
--   Re-running it manually against an already-created schema will encounter
--   existing-table / duplicate-seed errors; use incremental migrations instead.
--
--   Password hashes in the demo users are placeholders, not usable passwords.
--   Replace them with hashes generated by your application before login.
-- ============================================================================

CREATE DATABASE IF NOT EXISTS pharmacy_marketplace_demo
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_0900_ai_ci;
USE pharmacy_marketplace_demo;

SET time_zone = '+00:00';

-- ---------------------------------------------------------------------------
-- 1. USERS, GLOBAL ROLES, AND PHARMACY MEMBERSHIP
-- ---------------------------------------------------------------------------

CREATE TABLE users (
    user_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    username VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(30) NULL,
    full_name VARCHAR(255) NOT NULL,
    account_status ENUM('ACTIVE', 'SUSPENDED', 'DISABLED') NOT NULL DEFAULT 'ACTIVE',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id),
    UNIQUE KEY uq_users_username (username),
    UNIQUE KEY uq_users_email (email),
    KEY idx_users_phone (phone)
) ENGINE=InnoDB;

CREATE TABLE system_roles (
    role_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    role_name VARCHAR(50) NOT NULL,
    description VARCHAR(255) NULL,
    PRIMARY KEY (role_id),
    UNIQUE KEY uq_system_roles_name (role_name)
) ENGINE=InnoDB;

CREATE TABLE user_system_roles (
    user_id BIGINT UNSIGNED NOT NULL,
    role_id INT UNSIGNED NOT NULL,
    assigned_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_system_roles_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_user_system_roles_role
        FOREIGN KEY (role_id) REFERENCES system_roles(role_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE pharmacies (
    pharmacy_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    pharmacy_name VARCHAR(255) NOT NULL,
    license_number VARCHAR(100) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    email VARCHAR(255) NULL,
    province VARCHAR(100) NULL,
    district VARCHAR(100) NULL,
    ward VARCHAR(100) NULL,
    street_address VARCHAR(500) NOT NULL,
    latitude DECIMAL(10,7) NULL,
    longitude DECIMAL(10,7) NULL,
    registration_status ENUM('PENDING', 'APPROVED', 'REJECTED', 'SUSPENDED') NOT NULL DEFAULT 'PENDING',
    is_searchable BOOLEAN NOT NULL DEFAULT FALSE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (pharmacy_id),
    UNIQUE KEY uq_pharmacies_license (license_number),
    KEY idx_pharmacies_search (registration_status, is_searchable),
    KEY idx_pharmacies_location (latitude, longitude),
    CONSTRAINT chk_pharmacy_search_requires_approval
        CHECK (is_searchable = FALSE OR registration_status = 'APPROVED'),
    CONSTRAINT chk_pharmacy_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_pharmacy_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
) ENGINE=InnoDB;

CREATE TABLE pharmacy_members (
    pharmacy_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    pharmacy_role ENUM('OWNER', 'MANAGER', 'STAFF') NOT NULL DEFAULT 'STAFF',
    member_status ENUM('INVITED', 'ACTIVE', 'DISABLED') NOT NULL DEFAULT 'ACTIVE',
    joined_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (pharmacy_id, user_id),
    KEY idx_pharmacy_members_user (user_id),
    CONSTRAINT fk_pharmacy_members_pharmacy
        FOREIGN KEY (pharmacy_id) REFERENCES pharmacies(pharmacy_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_pharmacy_members_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE pharmacy_verifications (
    verification_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    pharmacy_id BIGINT UNSIGNED NOT NULL,
    admin_id BIGINT UNSIGNED NULL,
    document_type VARCHAR(100) NOT NULL,
    document_path VARCHAR(500) NOT NULL,
    decision ENUM('PENDING', 'APPROVED', 'REJECTED') NOT NULL DEFAULT 'PENDING',
    remarks TEXT NULL,
    submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at DATETIME NULL,
    PRIMARY KEY (verification_id),
    KEY idx_pharmacy_verifications_pharmacy (pharmacy_id, submitted_at),
    KEY idx_pharmacy_verifications_admin (admin_id),
    CONSTRAINT fk_pharmacy_verifications_pharmacy
        FOREIGN KEY (pharmacy_id) REFERENCES pharmacies(pharmacy_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_pharmacy_verifications_admin
        FOREIGN KEY (admin_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------------
-- 2. CENTRAL MEDICINE CATALOG AND PHARMACY-SPECIFIC PRODUCTS / STOCK
-- ---------------------------------------------------------------------------

CREATE TABLE medicines (
    medicine_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    canonical_name VARCHAR(255) NOT NULL,
    strength VARCHAR(100) NULL,
    dosage_form VARCHAR(100) NULL,
    route_of_administration VARCHAR(100) NULL,
    manufacturer_name VARCHAR(255) NULL,
    description TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (medicine_id),
    KEY idx_medicines_name (canonical_name),
    KEY idx_medicines_active (is_active)
) ENGINE=InnoDB;

-- Store active ingredients separately so combination medicines can have
-- multiple ingredients. `ingredient_strength` is the amount of this ingredient
-- in the represented medicine unit, e.g. 500 mg.
CREATE TABLE medicine_ingredients (
    medicine_id BIGINT UNSIGNED NOT NULL,
    ingredient_name VARCHAR(255) NOT NULL,
    ingredient_strength VARCHAR(100) NULL,
    PRIMARY KEY (medicine_id, ingredient_name),
    KEY idx_medicine_ingredients_name (ingredient_name),
    CONSTRAINT fk_medicine_ingredients_medicine
        FOREIGN KEY (medicine_id) REFERENCES medicines(medicine_id)
        ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE medicine_categories (
    category_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    category_name VARCHAR(100) NOT NULL,
    parent_category_id INT UNSIGNED NULL,
    description VARCHAR(255) NULL,
    PRIMARY KEY (category_id),
    UNIQUE KEY uq_medicine_categories_parent_name (parent_category_id, category_name),
    CONSTRAINT fk_medicine_categories_parent
        FOREIGN KEY (parent_category_id) REFERENCES medicine_categories(category_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE medicine_category_mapping (
    medicine_id BIGINT UNSIGNED NOT NULL,
    category_id INT UNSIGNED NOT NULL,
    PRIMARY KEY (medicine_id, category_id),
    KEY idx_medicine_category_mapping_category (category_id),
    CONSTRAINT fk_mcm_medicine
        FOREIGN KEY (medicine_id) REFERENCES medicines(medicine_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_mcm_category
        FOREIGN KEY (category_id) REFERENCES medicine_categories(category_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

-- A PharmacyProduct is a pharmacy's own listing. Composite keys below allow
-- order_items to enforce that the product and pharmacy order belong together.
-- medicine_id may be NULL when
-- a pharmacy has registered a product that has not yet been matched to the
-- central catalog. Price and availability are pharmacy-specific.
CREATE TABLE pharmacy_products (
    pharmacy_product_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    pharmacy_id BIGINT UNSIGNED NOT NULL,
    medicine_id BIGINT UNSIGNED NULL,
    local_product_name VARCHAR(255) NOT NULL,
    package_description VARCHAR(100) NULL,
    barcode VARCHAR(100) NULL,
    selling_price DECIMAL(12,2) NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (pharmacy_product_id),
    KEY idx_pharmacy_products_pharmacy_medicine (pharmacy_id, medicine_id),
    UNIQUE KEY uq_pharmacy_product_id_pharmacy (pharmacy_product_id, pharmacy_id),
    UNIQUE KEY uq_pharmacy_product_barcode (pharmacy_id, barcode),
    KEY idx_pharmacy_products_medicine (medicine_id),
    KEY idx_pharmacy_products_search (pharmacy_id, is_available),
    CONSTRAINT fk_pharmacy_products_pharmacy
        FOREIGN KEY (pharmacy_id) REFERENCES pharmacies(pharmacy_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_pharmacy_products_medicine
        FOREIGN KEY (medicine_id) REFERENCES medicines(medicine_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT chk_pharmacy_products_price CHECK (selling_price >= 0)
) ENGINE=InnoDB;

-- quantity_on_hand is the physical stock. quantity_reserved is the portion
-- temporarily held for orders. Available stock = on_hand - reserved.
CREATE TABLE inventory_batches (
    batch_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    pharmacy_product_id BIGINT UNSIGNED NOT NULL,
    batch_number VARCHAR(100) NOT NULL,
    quantity_on_hand INT UNSIGNED NOT NULL DEFAULT 0,
    quantity_reserved INT UNSIGNED NOT NULL DEFAULT 0,
    expiration_date DATE NOT NULL,
    purchase_price DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (batch_id),
    UNIQUE KEY uq_inventory_batch_number (pharmacy_product_id, batch_number),
    UNIQUE KEY uq_inventory_batch_id_product (batch_id, pharmacy_product_id),
    KEY idx_inventory_batches_expiration (expiration_date),
    KEY idx_inventory_batches_product (pharmacy_product_id),
    CONSTRAINT fk_inventory_batches_product
        FOREIGN KEY (pharmacy_product_id) REFERENCES pharmacy_products(pharmacy_product_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_inventory_reserved_not_over_on_hand
        CHECK (quantity_reserved <= quantity_on_hand),
    CONSTRAINT chk_inventory_purchase_price CHECK (purchase_price >= 0)
) ENGINE=InnoDB;

CREATE TABLE stock_transactions (
    stock_transaction_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    batch_id BIGINT UNSIGNED NOT NULL,
    transaction_type ENUM('PURCHASE', 'SALE', 'CUSTOMER_RETURN', 'SUPPLIER_RETURN', 'ADJUSTMENT', 'TRANSFER_IN', 'TRANSFER_OUT') NOT NULL,
    quantity_change INT NOT NULL,
    reference_type VARCHAR(50) NULL,
    reference_id BIGINT UNSIGNED NULL,
    performed_by BIGINT UNSIGNED NULL,
    notes TEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (stock_transaction_id),
    KEY idx_stock_transactions_batch_date (batch_id, created_at),
    KEY idx_stock_transactions_reference (reference_type, reference_id),
    KEY idx_stock_transactions_user (performed_by),
    CONSTRAINT fk_stock_transactions_batch
        FOREIGN KEY (batch_id) REFERENCES inventory_batches(batch_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_stock_transactions_user
        FOREIGN KEY (performed_by) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT chk_stock_transaction_nonzero CHECK (quantity_change <> 0)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------------
-- 3. PRESCRIPTIONS
-- ---------------------------------------------------------------------------

CREATE TABLE prescriptions (
    prescription_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    customer_id BIGINT UNSIGNED NOT NULL,
    image_path VARCHAR(500) NOT NULL,
    processing_status ENUM('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED') NOT NULL DEFAULT 'PENDING',
    verification_status ENUM('PENDING', 'VERIFIED', 'REJECTED') NOT NULL DEFAULT 'PENDING',
    reviewed_by BIGINT UNSIGNED NULL,
    review_notes TEXT NULL,
    uploaded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at DATETIME NULL,
    PRIMARY KEY (prescription_id),
    KEY idx_prescriptions_customer (customer_id, uploaded_at),
    KEY idx_prescriptions_status (processing_status, verification_status),
    CONSTRAINT fk_prescriptions_customer
        FOREIGN KEY (customer_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_prescriptions_reviewer
        FOREIGN KEY (reviewed_by) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE prescription_items (
    prescription_item_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    prescription_id BIGINT UNSIGNED NOT NULL,
    medicine_id BIGINT UNSIGNED NULL,
    recognized_name VARCHAR(255) NOT NULL,
    required_quantity INT UNSIGNED NULL,
    dosage_instruction TEXT NULL,
    recognition_confidence DECIMAL(5,2) NULL,
    PRIMARY KEY (prescription_item_id),
    KEY idx_prescription_items_prescription (prescription_id),
    KEY idx_prescription_items_medicine (medicine_id),
    CONSTRAINT fk_prescription_items_prescription
        FOREIGN KEY (prescription_id) REFERENCES prescriptions(prescription_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_prescription_items_medicine
        FOREIGN KEY (medicine_id) REFERENCES medicines(medicine_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT chk_prescription_required_quantity
        CHECK (required_quantity IS NULL OR required_quantity > 0),
    CONSTRAINT chk_prescription_confidence
        CHECK (recognition_confidence IS NULL OR recognition_confidence BETWEEN 0 AND 100)
) ENGINE=InnoDB;

