        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_cart_item_quantity CHECK (quantity > 0)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------------
-- 5. ORDERS: ONE CUSTOMER ORDER CAN BE SPLIT INTO MANY PHARMACY ORDERS
-- ---------------------------------------------------------------------------

CREATE TABLE customer_orders (
    order_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_number VARCHAR(40) NOT NULL,
    customer_id BIGINT UNSIGNED NOT NULL,
    prescription_id BIGINT UNSIGNED NULL,
    address_id BIGINT UNSIGNED NULL,
    recipient_name VARCHAR(255) NOT NULL,
    recipient_phone VARCHAR(30) NOT NULL,
    shipping_province VARCHAR(100) NOT NULL,
    shipping_district VARCHAR(100) NOT NULL,
    shipping_ward VARCHAR(100) NULL,
    shipping_street_address VARCHAR(500) NOT NULL,
    shipping_latitude DECIMAL(10,7) NULL,
    shipping_longitude DECIMAL(10,7) NULL,
    subtotal DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    shipping_fee DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    discount_amount DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    total_amount DECIMAL(14,2) GENERATED ALWAYS AS (subtotal + shipping_fee - discount_amount) STORED,
    order_status ENUM('PENDING', 'CONFIRMED', 'PROCESSING', 'PARTIALLY_COMPLETED', 'COMPLETED', 'CANCELLED') NOT NULL DEFAULT 'PENDING',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (order_id),
    UNIQUE KEY uq_customer_orders_number (order_number),
    KEY idx_customer_orders_customer_date (customer_id, created_at),
    KEY idx_customer_orders_status (order_status, created_at),
    CONSTRAINT fk_customer_orders_customer
        FOREIGN KEY (customer_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_customer_orders_prescription
        FOREIGN KEY (prescription_id) REFERENCES prescriptions(prescription_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_customer_orders_address
        FOREIGN KEY (address_id) REFERENCES customer_addresses(address_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT chk_customer_order_amounts
        CHECK (subtotal >= 0 AND shipping_fee >= 0 AND discount_amount >= 0 AND discount_amount <= subtotal + shipping_fee),
    CONSTRAINT chk_customer_order_latitude
        CHECK (shipping_latitude IS NULL OR shipping_latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_customer_order_longitude
        CHECK (shipping_longitude IS NULL OR shipping_longitude BETWEEN -180 AND 180)
) ENGINE=InnoDB;

CREATE TABLE pharmacy_orders (
    pharmacy_order_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_id BIGINT UNSIGNED NOT NULL,
    pharmacy_id BIGINT UNSIGNED NOT NULL,
    subtotal DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    shipping_fee DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    discount_amount DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    total_amount DECIMAL(14,2) GENERATED ALWAYS AS (subtotal + shipping_fee - discount_amount) STORED,
    order_status ENUM('PENDING', 'ACCEPTED', 'REJECTED', 'PREPARING', 'READY_FOR_PICKUP', 'SHIPPED', 'COMPLETED', 'CANCELLED') NOT NULL DEFAULT 'PENDING',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (pharmacy_order_id),
    UNIQUE KEY uq_pharmacy_order_per_pharmacy (order_id, pharmacy_id),
    UNIQUE KEY uq_pharmacy_order_id_pharmacy (pharmacy_order_id, pharmacy_id),
    KEY idx_pharmacy_orders_pharmacy_status (pharmacy_id, order_status, created_at),
    CONSTRAINT fk_pharmacy_orders_order
        FOREIGN KEY (order_id) REFERENCES customer_orders(order_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_pharmacy_orders_pharmacy
        FOREIGN KEY (pharmacy_id) REFERENCES pharmacies(pharmacy_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_pharmacy_order_amounts
        CHECK (subtotal >= 0 AND shipping_fee >= 0 AND discount_amount >= 0 AND discount_amount <= subtotal + shipping_fee)
) ENGINE=InnoDB;

CREATE TABLE order_items (
    order_item_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    pharmacy_order_id BIGINT UNSIGNED NOT NULL,
    pharmacy_id BIGINT UNSIGNED NOT NULL,
    pharmacy_product_id BIGINT UNSIGNED NOT NULL,
    prescription_item_id BIGINT UNSIGNED NULL,
    medicine_name_snapshot VARCHAR(255) NOT NULL,
    quantity INT UNSIGNED NOT NULL,
    unit_price DECIMAL(12,2) NOT NULL,
    line_total DECIMAL(14,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    PRIMARY KEY (order_item_id),
    UNIQUE KEY uq_order_item_product (pharmacy_order_id, pharmacy_product_id),
    UNIQUE KEY uq_order_item_id_product (order_item_id, pharmacy_product_id),
    KEY idx_order_items_pharmacy_order (pharmacy_order_id),
    KEY idx_order_items_product (pharmacy_product_id),
    KEY idx_order_items_prescription_item (prescription_item_id),
    CONSTRAINT fk_order_items_prescription_item
        FOREIGN KEY (prescription_item_id) REFERENCES prescription_items(prescription_item_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_order_items_pharmacy_order_pharmacy
        FOREIGN KEY (pharmacy_order_id, pharmacy_id)
        REFERENCES pharmacy_orders(pharmacy_order_id, pharmacy_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_product_pharmacy
        FOREIGN KEY (pharmacy_product_id, pharmacy_id)
        REFERENCES pharmacy_products(pharmacy_product_id, pharmacy_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_order_item_unit_price CHECK (unit_price >= 0)
) ENGINE=InnoDB;

CREATE TABLE inventory_reservations (
    reservation_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_item_id BIGINT UNSIGNED NOT NULL,
    pharmacy_product_id BIGINT UNSIGNED NOT NULL,
    batch_id BIGINT UNSIGNED NOT NULL,
    quantity_reserved INT UNSIGNED NOT NULL,
    reservation_status ENUM('ACTIVE', 'CONSUMED', 'RELEASED', 'EXPIRED') NOT NULL DEFAULT 'ACTIVE',
    expires_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (reservation_id),
    UNIQUE KEY uq_reservation_item_batch (order_item_id, batch_id),
    KEY idx_inventory_reservations_batch_status (batch_id, reservation_status),
    CONSTRAINT fk_inventory_reservations_order_item_product
        FOREIGN KEY (order_item_id, pharmacy_product_id)
        REFERENCES order_items(order_item_id, pharmacy_product_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_reservations_batch_product
        FOREIGN KEY (batch_id, pharmacy_product_id)
        REFERENCES inventory_batches(batch_id, pharmacy_product_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_inventory_reservation_quantity CHECK (quantity_reserved > 0)
) ENGINE=InnoDB;

CREATE TABLE order_status_history (
    history_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_id BIGINT UNSIGNED NULL,
    pharmacy_order_id BIGINT UNSIGNED NULL,
    old_status VARCHAR(50) NULL,
    new_status VARCHAR(50) NOT NULL,
    changed_by BIGINT UNSIGNED NULL,
    remarks TEXT NULL,
    changed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (history_id),
    KEY idx_order_status_history_order (order_id, changed_at),
    KEY idx_order_status_history_pharmacy_order (pharmacy_order_id, changed_at),
    CONSTRAINT fk_order_status_history_order
        FOREIGN KEY (order_id) REFERENCES customer_orders(order_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_order_status_history_pharmacy_order
        FOREIGN KEY (pharmacy_order_id) REFERENCES pharmacy_orders(pharmacy_order_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_order_status_history_user
